import type { Metadata } from "next";
import { Geist, Geist_Mono } from "next/font/google";
import "./globals.css";

const geistSans = Geist({
  variable: "--font-geist-sans",
  subsets: ["latin"],
});

const geistMono = Geist_Mono({
  variable: "--font-geist-mono",
  subsets: ["latin"],
});

import { getConfig } from "@/lib/stats";

export async function generateMetadata(): Promise<Metadata> {
  const config = getConfig();
  return {
    title: `${config.siteName} - Free Online Video Downloader`,
    description: `Download videos from YouTube, TikTok, Instagram, Facebook, and more in HD quality for free with ${config.siteName}.`,
  };
}

export default function RootLayout({ children }: LayoutProps<"/">) {
  return (
    <html
      lang="en"
      className={`${geistSans.variable} ${geistMono.variable} h-full antialiased`}
    >
      <body className="min-h-full flex flex-col">{children}</body>
    </html>
  );
}
